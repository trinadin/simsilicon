        private static bool LiveLeg(Action<string> log)
        {
            var screen = FSO.Client.GameFacade.Screens?.CurrentUIScreen as UI.Screens.TS1GameScreen;
            var mp = screen?.Frontend?.MainPanel;
            if (mp == null) { log("AUTOTEST ui39 live: no main panel"); return false; }
            var prevMode = mp.Mode;
            var set = FSO.Client.GlobalSettings.Default;
            bool keepQuickTips = set.TS1QuickTips;
            bool ok = true; string info = "";
            try
            {
                mp.SetMode(UI.Panels.UIMainPanelMode.OPTIONS);
                var panel = mp.SubPanel as UI.Panels.LiveSubpanels.UIOriginalOptionsPanel;
                if (panel == null) { mp.Switcher_OnCategorySelect(0); panel = mp.SubPanel as UI.Panels.LiveSubpanels.UIOriginalOptionsPanel; }
                if (panel == null) { log("AUTOTEST ui39 live: no options panel"); return false; }
                panel.ShowScreen("play");
                var fwRow = panel.Rows.FirstOrDefault(r => r.CaptionIndex == 59);   // About Free Will
                var qtRow = panel.Rows.FirstOrDefault(r => r.CaptionIndex == 72);   // Quick Tips itself
                var esRow = panel.Rows.FirstOrDefault(r => r.CaptionIndex == 62);   // Edge Scrolling
                if (fwRow == null || qtRow == null || esRow == null)
                { log("AUTOTEST ui39 live: rows missing"); return false; }

                set.TS1QuickTips = true;
                panel.ClosePopup();

                // -- the dwell law (the production pump method, synthetic hover
                //    row + clock = the disclosed probe seam)
                if (UI.Panels.LiveSubpanels.UIOriginalOptionsPanel.QuickTipDwellMs != 250 || !panel.QuickTipsEnabled) { ok = false; info += "dwell/enable;"; }
                panel.QuickTipProcess(fwRow, 1000);
                if (panel.CurrentPopup != null) { ok = false; info += "preDwell;"; }
                panel.QuickTipProcess(fwRow, 1249);
                if (panel.CurrentPopup != null) { ok = false; info += "dwell249;"; }
                panel.QuickTipProcess(fwRow, 1250);   // now-start == 250 -> fires
                var pop = panel.CurrentPopup;
                if (pop == null || !ReferenceEquals(pop.Row, fwRow) || panel.QuickTipOpenedRow != fwRow)
                { ok = false; info += "dwell250;"; }
                else if (pop.Title != fwRow.AboutTitle || pop.Body != fwRow.AboutBody
                    || pop.Member.ToLowerInvariant() != "cpanel\\popupoptfreewill.bmp"
                    || pop.Parent != panel.DynamicOverlay
                    || pop.Size.X != UI.Panels.LiveSubpanels.UIOptionAboutPopup.WindowWidth)
                { ok = false; info += "content;"; }

                // -- hover-out dismiss (native 0x14 same-button DisablePopup)
                panel.QuickTipProcess(null, 1300);
                if (panel.CurrentPopup != null || panel.QuickTipOpenedRow != null) { ok = false; info += "dismiss;"; }

                // -- second row retarget through its own dwell
                panel.QuickTipProcess(qtRow, 2000);
                panel.QuickTipProcess(qtRow, 2250);
                pop = panel.CurrentPopup;
                if (pop == null || !ReferenceEquals(pop.Row, qtRow)
                    || pop.Title != "About Quick Tips"
                    || pop.Body != "Displays help popup windows without pausing or requiring a mouse click.")
                { ok = false; info += "retarget;"; }
                panel.QuickTipProcess(null, 2300);

                // -- same-button toggle against a CLICK-opened popup (native
                //    0x13 on the popup's own button closes it)
                panel.OpenPopup(fwRow);
                if (panel.CurrentPopup == null) { ok = false; info += "clickOpen;"; }
                else
                {
                    panel.QuickTipProcess(fwRow, 3000);
                    panel.QuickTipProcess(fwRow, 3250);
                    if (panel.CurrentPopup != null) { ok = false; info += "sameBtnToggle;"; }
                }
                panel.ClosePopup();

                // -- the option gate: OFF disarms (no popup after any dwell)
                set.TS1QuickTips = false;
                panel.QuickTipProcess(esRow, 5000);
                panel.QuickTipProcess(esRow, 20000);
                if (panel.CurrentPopup != null) { ok = false; info += "offDisarm;"; }
                // the row's own production Toggle drives the gate (the native
                // checkbox cmd): off -> on
                // the row's live IsOn reflects the gate (false while off)
                if (qtRow.IsOn == null || qtRow.IsOn()) { ok = false; info += "offState;"; }
                if (qtRow.Toggle != null)
                {
                    qtRow.Toggle();
                    if (!set.TS1QuickTips || !panel.QuickTipsEnabled) { ok = false; info += "rowToggle;"; }
                }
                // and re-arms the dwell
                panel.QuickTipProcess(esRow, 21000);
                panel.QuickTipProcess(esRow, 21250);
                if (panel.CurrentPopup == null || !ReferenceEquals(panel.CurrentPopup.Row, esRow))
                { ok = false; info += "onRearm;"; }
                panel.QuickTipProcess(null, 22000);
            }
            catch (Exception ex)
            {
                log("AUTOTEST ui39 live EXC " + ex.GetType().Name + " " + ex.Message);
                ok = false;
            }
            finally
            {
                try { (mp.SubPanel as UI.Panels.LiveSubpanels.UIOriginalOptionsPanel)?.ClosePopup(); } catch { }
                set.TS1QuickTips = keepQuickTips;
                set.Save();
                mp.SetMode(prevMode == UI.Panels.UIMainPanelMode.OPTIONS
                    ? UI.Panels.UIMainPanelMode.LIVE : prevMode);
            }
            log("AUTOTEST ui39 live: " + (ok ? "OK" : "FAIL " + info));
            return ok;
        }

        // ------------------------------------------------------------------
        // UI-39b: the camera-panel Quick Tips surface (STR# 140 [16]/[17] +
        // [18]/[19] group popups into the SAME cWinLivePopup presenter). The
        // camera panel's own Update pump calls the same QuickTipProcess; the
        // synthetic hover group + clock are the disclosed probe seam.
        private static bool CamLiveLeg(Action<string> log)
        {
            var screen = FSO.Client.GameFacade.Screens?.CurrentUIScreen as UI.Screens.TS1GameScreen;
            var mp = screen?.Frontend?.MainPanel;
            if (mp == null) { log("AUTOTEST ui39 cam: no main panel"); return false; }
            var prevMode = mp.Mode;
            var set = FSO.Client.GlobalSettings.Default;
            bool keepQuickTips = set.TS1QuickTips;
            bool ok = true; string info = "";
            try
            {
                mp.SetMode(UI.Panels.UIMainPanelMode.CAMERA);
                var cam = mp.CameraChrome;
                if (cam == null) { log("AUTOTEST ui39 cam: no camera chrome"); return false; }
                set.TS1QuickTips = true;
                cam.ClosePopup();
                var snap = cam.SnapshotSizeTip;
                var qual = cam.QualitySettingTip;
                if (snap == null || qual == null) { ok = false; info += "groups;"; }
                else
                {
                    // canon surface mapping: the camera panel's quick-tips are
                    // the two GROUP popups, not the per-button one-liners.
                    if (snap.Title != "Snapshot Sizes"
                        || !snap.Body.StartsWith("Snapshots come in three sizes"))
                    { ok = false; info += "snapCanon;"; }
                    if (qual.Title != "Quality Settings"
                        || !qual.Body.StartsWith("Choose low, medium, or high quality settings"))
                    { ok = false; info += "qualCanon;"; }
                    // the group art resolves through the Res_*.h/RT -> FAR map
                    // (kCamPopupDetail 0x455 / kCamPopupQualDetail 0x456 —
                    // cWinCamPanel::Init @0x266c2c/@0x266c38).
                    if (snap.Member == null || snap.Art == null) { ok = false; info += "snapArt;"; }
                    if (qual.Member == null || qual.Art == null) { ok = false; info += "qualArt;"; }
                    // dwell law through the production pump (synthetic hover +
                    // clock = the disclosed probe seam)
                    cam.QuickTipProcess(snap, 1000);
                    if (cam.CurrentPopup != null) { ok = false; info += "preDwell;"; }
                    cam.QuickTipProcess(snap, 1249);
                    if (cam.CurrentPopup != null) { ok = false; info += "dwell249;"; }
                    cam.QuickTipProcess(snap, 1250);
                    var pop = cam.CurrentPopup;
                    if (pop == null || !ReferenceEquals(pop.Row, snap.Row) || cam.QuickTipOpenedGroup != snap)
                    { ok = false; info += "dwell250;"; }
                    else if (pop.Title != "Snapshot Sizes" || pop.Art != snap.Art
                        || pop.Parent != cam.QuickTipOverlay
                        || pop.Size.X != UI.Panels.LiveSubpanels.UIOptionAboutPopup.WindowWidth)
                    { ok = false; info += "snapContent;"; }
                    // hover-out dismiss (native 0x14 same-button DisablePopup)
                    cam.QuickTipProcess(null, 1300);
                    if (cam.CurrentPopup != null || cam.QuickTipOpenedGroup != null) { ok = false; info += "dismiss;"; }
                    // quality group retarget through its own dwell
                    cam.QuickTipProcess(qual, 2000);
                    cam.QuickTipProcess(qual, 2250);
                    pop = cam.CurrentPopup;
                    if (pop == null || !ReferenceEquals(pop.Row, qual.Row)
                        || pop.Title != "Quality Settings" || pop.Art != qual.Art)
                    { ok = false; info += "qualRetarget;"; }
                    cam.QuickTipProcess(null, 2300);
                    // the option gate: OFF disarms (no popup after any dwell)
                    set.TS1QuickTips = false;
                    cam.QuickTipProcess(snap, 5000);
                    cam.QuickTipProcess(snap, 20000);
                    if (cam.CurrentPopup != null) { ok = false; info += "offDisarm;"; }
                    set.TS1QuickTips = true;
                }
            }
            catch (Exception ex)
            {
                log("AUTOTEST ui39 cam EXC " + ex.GetType().Name + " " + ex.Message);
                ok = false;
            }
            finally
            {
                try { mp.CameraChrome?.ClosePopup(); } catch { }
                set.TS1QuickTips = keepQuickTips;
                set.Save();
                mp.SetMode(prevMode == UI.Panels.UIMainPanelMode.CAMERA
                    ? UI.Panels.UIMainPanelMode.LIVE : prevMode);
            }
            log("AUTOTEST ui39 cam: " + (ok ? "OK" : "FAIL " + info));
            return ok;
        }
