        public static bool Run(Action<string> log)
        {
            bool canon = CanonLeg(log);
            bool law = BinaryLawLeg(log);
            bool live = LiveLeg(log);
            bool cam = CamLiveLeg(log);
            log("AUTOTEST ui39: canon=" + canon + " law=" + law + " live=" + live + " cam=" + cam);
            return canon && law && live && cam;
        }

        // ------------------------------------------------------------------
        private static string Hash(byte[] b)
        {
            using (var sha = SHA256.Create()) return ConvertHex(sha.ComputeHash(b));
        }

        private static string ConvertHex(byte[] b)
        {
            var sb = new System.Text.StringBuilder();
            foreach (var x in b) sb.Append(x.ToString("x2"));
            return sb.ToString();
        }

        /// Walk UIText.iff linearly from 0x40 (r121 idiom; 60-byte Maxis
        /// header, 76-byte chunk headers, BE sizes; full-chunk sha includes
        /// the header — the gate convention).
        private static byte[] FindStrChunk(byte[] d, int wanted, out string label, out List<string> english)
        {
            label = null; english = null;
            int off = 0x40;
            while (off + 76 <= d.Length)
            {
                int sz = (d[off + 4] << 24) | (d[off + 5] << 16) | (d[off + 6] << 8) | d[off + 7];
                if (sz < 76 || off + sz > d.Length) break;
                int cid = (d[off + 8] << 8) | d[off + 9];
                if (cid == wanted)
                {
                    // runner convention: ASCII decode (ReadCStringAt) — the
                    // pinned tables' labels and English entries are ASCII
                    var lblb = new byte[64];
                    Array.Copy(d, off + 12, lblb, 0, 64);
                    label = System.Text.Encoding.ASCII.GetString(lblb).Split('\0')[0];
                    var raw = new byte[sz];
                    Array.Copy(d, off, raw, 0, sz);
                    english = ParseEnglish(raw);
                    return raw;
                }
                off += sz;
            }
            return null;
        }

        /// format -3 {u8 lang, cstring value, cstring comment}; lang 1 first.
        private static List<string> ParseEnglish(byte[] raw)
        {
            var result = new List<string>();
            int count = raw[76 + 2] | (raw[76 + 3] << 8);
            if (count > 5000) count = 5000;
            int p = 76 + 4;
            int shown = 0;
            while (shown < count && p + 1 < raw.Length)
            {
                int lang = raw[p]; p++;
                int e = Array.IndexOf(raw, (byte)0, p);
                if (e < 0) break;
                if (lang == 1) result.Add(System.Text.Encoding.ASCII.GetString(raw, p, e - p));
                p = e + 1;
                e = Array.IndexOf(raw, (byte)0, p);
                if (e < 0) break;
                p = e + 1;
                shown++;
            }
            return result;
        }

        private static bool CanonLeg(Action<string> log)
        {
            var path = Path.Combine(FSO.Content.Content.TS1HybridBasePath, "GameData/UIText.iff");
            if (!File.Exists(path)) { log("AUTOTEST ui39 canon: no UIText.iff"); return false; }
            var d = File.ReadAllBytes(path);
            string lbl; List<string> e140, e145;
            var raw140 = FindStrChunk(d, 140, out lbl, out e140);
            var raw145 = FindStrChunk(d, 145, out _, out e145);
            bool ok = raw140 != null && raw145 != null;
            string info = "";
            if (ok)
            {
                if (lbl != Ui39CamModesLabel || Hash(raw140) != Ui39CamModesSha || e140.Count != Ui39CamModesEnglish)
                { ok = false; info += "140(" + lbl + "/" + e140.Count + ");"; }
                // the quick-tip payloads: 8 tooltips + 2 popup title/body pairs
                int[] tips = { 1, 3, 5, 7, 9, 11, 13, 15 };
                string[] tipStrs = { "Small-Sized Snapshot", "Medium-Sized Snapshot", "Large-Sized Snapshot",
                    "Custom-Sized Snapshot", "View Photo Album", "Low Quality", "Medium Quality", "High Quality" };
                for (int i = 0; i < tips.Length; i++)
                    if (e140[tips[i]] != tipStrs[i]) { ok = false; info += "140[" + tips[i] + "];"; break; }
                if (e140[16] != "Snapshot Sizes" || e140[18] != "Quality Settings"
                    || !e140[17].StartsWith("Snapshots come in three sizes")
                    || !e140[19].StartsWith("Choose low, medium, or high quality settings"))
                { ok = false; info += "140pairs;"; }
                // (x;y) directives parse with the panel's own production parser
                var p0 = UI.Panels.LiveSubpanels.UIOriginalOptionsPanel.ParseCanonPos(e140[0]);
                if (p0 == null || p0.Value.X != 82 || p0.Value.Y != 70) { ok = false; info += "140dir;"; }
                // the Quick Tips row's own canon strings (145 [72]/[73]/[74])
                if (e145.Count <= 83 || e145[72] != "Quick Tips" || e145[73] != "About Quick Tips"
                    || e145[74] != "Displays help popup windows without pausing or requiring a mouse click.")
                { ok = false; info += "145row;"; }
            }
            else info += "chunk-missing(140=" + (raw140 != null) + ",145=" + (raw145 != null) + ");";
            log("AUTOTEST ui39 canon: " + (ok ? "OK" : "FAIL " + info));
            return ok;
        }

        private static bool BinaryLawLeg(Action<string> log)
        {
            // uiopts pins UIText.iff at TS1HybridBasePath/GameData — so the
            // base path is game-data/The Sims and the engine binary sits
            // directly inside it.
            var path = Path.Combine(FSO.Content.Content.TS1HybridBasePath, Ui39BinaryPath);
            if (!File.Exists(path)) { log("AUTOTEST ui39 law: no binary at " + path); return false; }
            var d = File.ReadAllBytes(path);
            bool ok = true; string info = "";
            var pins = new[]
            {
                new[] { Ui39SetQuickTipsLawSha, "239ce0", "60" },
                new[] { Ui39TSPaintTipPumpSha, "50cff0", "80" },
                new[] { Ui39MouseEnterArmSha, "50b8a0", "40" },
                new[] { Ui39MouseExitSendSha, "50b460", "44" },
                new[] { Ui39Cmd13PopupBlockSha, "282b04", "136" },
            };
            foreach (var pin in pins)
            {
                int off = Convert.ToInt32(pin[1], 16);
                int len = int.Parse(pin[2]);
                if (off + len > d.Length || Hash(d[off..(off + len)]) != pin[0])
                { ok = false; info += pin[1] + ";"; }
            }
            // semantic immediates inside the pinned bodies: the dwell pair
            // li 0xFA (250 ON) + the OFF leg's 0x14D (333)/0x2EE (750) lis,
            // and the SendButtonCommand(0x13) in the TSPaint pump.
            if (ok)
            {
                int[] setQk = Words(d, 0x239ce0, 60);
                int[] pump = Words(d, 0x50cff0, 80);
                bool imm = setQk.Contains(0x380000FA) && setQk.Contains(0x3800014D)
                    && setQk.Contains(0x386002EE)
                    && pump.Contains(0x38800013);
                if (!imm) { ok = false; info += "immediates;"; }
            }
            log("AUTOTEST ui39 law: " + (ok ? "OK" : "FAIL " + info));
            return ok;
        }

        private static int[] Words(byte[] d, int off, int len)
        {
            var w = new int[len / 4];
            for (int i = 0; i < w.Length; i++)
                w[i] = (d[off + i * 4] << 24) | (d[off + i * 4 + 1] << 16)
                    | (d[off + i * 4 + 2] << 8) | d[off + i * 4 + 3];
            return w;
        }

