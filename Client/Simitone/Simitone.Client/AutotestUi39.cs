        private const string Ui39TSPaintTipPumpSha = "771eec0445d2355d5ec93ec319689146eb2f41a1d4a226830c4f219602eff16c";  // [0x50cff0 +80]
        private const string Ui39MouseEnterArmSha = "8a2642cc6f5bb7bf1b81d3521c91a727b6eafb469bd46648750ca44e9a42b819";  // [0x50b8a0 +40]
