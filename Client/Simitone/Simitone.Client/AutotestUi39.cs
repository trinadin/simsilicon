    ///     cTSWinBtn::TSPaint tip pump 0x50cff0 (+80), TSOnMouseEnter arm
    ///     0x50b8a0 (+40), TSOnMouseExit 0x14 send 0x50b460 (+44), and the
    ///     cWinOptions cmd-0x13/0x14 popup block 0x282b04 (+136); plus the
