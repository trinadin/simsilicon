    ///
    /// (1) DISK CANON — STR# 140 'cammodestrs' (the camera panel quick-tip
    ///     table cWinCamPanel::Init loads @0x266c8c): full-chunk sha, 20
    ///     English entries, the 8 button tooltips, both group popup pairs
